CREATE SCHEMA IF NOT EXISTS coldchain_web;
CREATE TABLE IF NOT EXISTS users (
  id BIGSERIAL PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL,
  password_hash VARCHAR(100) NOT NULL, role VARCHAR(30) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email ON users (lower(email));
CREATE TABLE IF NOT EXISTS products (
  id BIGSERIAL PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL,
  min_temp NUMERIC(5,1) NOT NULL, max_temp NUMERIC(5,1) NOT NULL,
  min_humidity NUMERIC(5,1) NOT NULL, max_humidity NUMERIC(5,1) NOT NULL,
  supplier_id BIGINT REFERENCES users(id), CHECK (min_temp < max_temp), CHECK (min_humidity < max_humidity));
CREATE TABLE IF NOT EXISTS shipments (
  id BIGSERIAL PRIMARY KEY, tracking_no VARCHAR(30) NOT NULL UNIQUE,
  product_id BIGINT NOT NULL REFERENCES products(id), quantity INT NOT NULL CHECK (quantity > 0),
  origin VARCHAR(100) NOT NULL, destination VARCHAR(100) NOT NULL, driver_id BIGINT REFERENCES users(id),
  status VARCHAR(20) NOT NULL DEFAULT 'CREATED'
    CHECK (status IN ('CREATED','IN_TRANSIT','DELIVERED','DELAYED','CANCELLED')),
  start_lat DOUBLE PRECISION NOT NULL, start_lon DOUBLE PRECISION NOT NULL,
  dest_lat DOUBLE PRECISION NOT NULL, dest_lon DOUBLE PRECISION NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS shipment_status_history (
  id BIGSERIAL PRIMARY KEY, shipment_id BIGINT NOT NULL REFERENCES shipments(id),
  from_status VARCHAR(20), to_status VARCHAR(20) NOT NULL, changed_by BIGINT REFERENCES users(id),
  note VARCHAR(200), changed_at TIMESTAMPTZ NOT NULL DEFAULT now());
-- SIMULATED readings and GPS positions (generated by software, no hardware)
CREATE TABLE IF NOT EXISTS sensor_readings (
  id BIGSERIAL PRIMARY KEY, shipment_id BIGINT NOT NULL REFERENCES shipments(id),
  sensor_id VARCHAR(30) NOT NULL, temperature NUMERIC(5,2) NOT NULL, humidity NUMERIC(5,2) NOT NULL,
  latitude DOUBLE PRECISION NOT NULL, longitude DOUBLE PRECISION NOT NULL,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS ix_readings_shipment_time ON sensor_readings (shipment_id, recorded_at);
CREATE TABLE IF NOT EXISTS alerts (
  id BIGSERIAL PRIMARY KEY, shipment_id BIGINT NOT NULL REFERENCES shipments(id),
  type VARCHAR(20) NOT NULL, severity VARCHAR(10) NOT NULL, message VARCHAR(300) NOT NULL,
  reading_value NUMERIC(6,2), status VARCHAR(15) NOT NULL DEFAULT 'OPEN'
    CHECK (status IN ('OPEN','ACKNOWLEDGED','RESOLVED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  acknowledged_by BIGINT REFERENCES users(id), acknowledged_at TIMESTAMPTZ,
  resolved_by BIGINT REFERENCES users(id), resolved_at TIMESTAMPTZ, resolution_note VARCHAR(500));
-- Duplicate-alert policy: only one unresolved alert per shipment and type
CREATE UNIQUE INDEX IF NOT EXISTS ux_alert_unresolved ON alerts (shipment_id, type) WHERE status <> 'RESOLVED';
CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGSERIAL PRIMARY KEY, actor_id BIGINT REFERENCES users(id), action VARCHAR(40) NOT NULL,
  detail VARCHAR(300), created_at TIMESTAMPTZ NOT NULL DEFAULT now());
